function glyph(slug) {
  for (const dir of dirs) {
    const file = join(dir, `${slug}.svg`);
    if (!existsSync(file)) continue;
    const path = readFileSync(file, "utf8").match(/ d="([^"]+)"/)?.[1];
    if (path) return path;
  }
  throw new Error(`no glyph for ${slug} in ${dirs.join(", ")}`);
}

/** Relative luminance (WCAG): a mark under 0.05 disappears on a dark surface, so dark mode draws it in the text colour. */
function luminance(hex) {
  const [r, g, b] = [0, 2, 4].map((at) => {
    const c = parseInt(hex.slice(at, at + 2), 16) / 255;
    return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

const rows = Object.entries(BRANDS).map(([id, spec]) => {
  if (spec.ms) return `  ${id}: { kind: "ms" },`;
  const color = `#${spec.color}`;
  const dark = luminance(spec.color) < 0.05 ? ", dark: true" : "";
  if (spec.letter) return `  ${id}: { kind: "letter", letter: ${JSON.stringify(spec.letter)}, color: "${color}"${dark} },`;
  return `  ${id}: { kind: "glyph", color: "${color}", path: ${JSON.stringify(glyph(spec.slug))}${dark} },`;
});

